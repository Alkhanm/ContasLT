-- Transferências entre contas: duas pernas (saída em uma conta, entrada em outra) vinculadas.
-- Os saldos das contas continuam contando cada perna; relatórios ignoram lançamentos com transfer_id.
CREATE TABLE transfers (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT    NOT NULL REFERENCES users (id),
    from_transaction_id BIGINT    NOT NULL UNIQUE REFERENCES transactions (id) ON DELETE CASCADE,
    to_transaction_id   BIGINT    NOT NULL UNIQUE REFERENCES transactions (id) ON DELETE CASCADE,
    created_at          TIMESTAMP NOT NULL
);

ALTER TABLE transactions ADD COLUMN transfer_id BIGINT REFERENCES transfers (id) ON DELETE SET NULL;
CREATE INDEX ix_tx_transfer ON transactions (transfer_id);

-- Pares que o usuário disse NÃO serem transferência no cruzamento automático. Cada lado é uma chave:
-- "bill:<id>" quando o lançamento é ocorrência de conta recorrente (a recusa vale para todas as ocorrências
-- daquelas duas regras, em qualquer mês) ou "tx:<id>" para um lançamento avulso. a_key < b_key, para a busca
-- não depender da ordem.
CREATE TABLE transfer_rejections (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    a_key      VARCHAR(40) NOT NULL,
    b_key      VARCHAR(40) NOT NULL,
    created_at TIMESTAMP   NOT NULL,
    CONSTRAINT uk_transfer_rejection UNIQUE (user_id, a_key, b_key)
);

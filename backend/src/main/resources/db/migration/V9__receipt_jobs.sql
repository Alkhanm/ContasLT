-- Fila de leitura de comprovantes: em produção não há modelo de visão no servidor; a foto fica guardada e um
-- worker no computador do usuário (com o Ollama local) puxa a tarefa, lê o cupom e devolve o resultado.
CREATE TABLE receipt_jobs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    -- Lançamento salvo com esta foto enquanto a leitura ainda não tinha acontecido; recebe os itens ao concluir.
    transaction_id BIGINT         REFERENCES transactions (id) ON DELETE SET NULL,
    receipt_file   VARCHAR(80)    NOT NULL,
    -- Chave de acesso lida do QR code na hora do envio (fonte mais confiável que o modelo).
    qr_access_key  VARCHAR(44),
    status         VARCHAR(10)    NOT NULL,
    attempts       INTEGER        NOT NULL DEFAULT 0,
    -- Enquanto RUNNING, o worker tem a tarefa até aqui; vencido o prazo, outro claim pode pegá-la de novo.
    leased_until   TIMESTAMP,
    -- JSON devolvido pelo modelo, guardado para o app montar a resposta quando o formulário ainda estiver aberto.
    result         VARCHAR(20000),
    error          VARCHAR(500),
    -- TRUE quando o resultado já foi entregue ao formulário (não aplicar de novo ao salvar).
    delivered      BOOLEAN        NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMP      NOT NULL,
    finished_at    TIMESTAMP
);
CREATE INDEX ix_receipt_jobs_status ON receipt_jobs (status, id);
CREATE INDEX ix_receipt_jobs_user_file ON receipt_jobs (user_id, receipt_file);

-- Situação da leitura adiada no próprio lançamento: PENDING (aguardando o worker), DIVERGENT (lido, mas o
-- total ou a data do cupom não batem com o lançado; receipt_scan_total/date guardam o que foi lido) ou FAILED.
ALTER TABLE transactions ADD COLUMN receipt_scan_status VARCHAR(10);
ALTER TABLE transactions ADD COLUMN receipt_scan_total  NUMERIC(14,2);
ALTER TABLE transactions ADD COLUMN receipt_scan_date   DATE;

-- Itens de um lançamento (produtos de um cupom fiscal) e dados do comprovante.
CREATE TABLE transaction_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT        NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
    position       INTEGER       NOT NULL,
    description    VARCHAR(140)  NOT NULL,
    quantity       NUMERIC(12,3),
    unit_price     NUMERIC(14,2),
    total          NUMERIC(14,2) NOT NULL
);
CREATE INDEX ix_item_tx ON transaction_items (transaction_id);

ALTER TABLE transactions ADD COLUMN merchant           VARCHAR(120);
ALTER TABLE transactions ADD COLUMN receipt_file       VARCHAR(80);
ALTER TABLE transactions ADD COLUMN receipt_access_key VARCHAR(44);
-- TRUE quando um lançamento já existente foi vinculado a uma linha do extrato importado
-- (em vez de criado por ele). Ao excluir a importação, esses são só desvinculados.
ALTER TABLE transactions ADD COLUMN linked_import BOOLEAN NOT NULL DEFAULT FALSE;
CREATE INDEX ix_tx_receipt_key ON transactions (user_id, receipt_access_key);

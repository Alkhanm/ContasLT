ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;
ALTER TABLE users ADD COLUMN google_sub VARCHAR(64);
ALTER TABLE users ADD CONSTRAINT uk_users_google_sub UNIQUE (google_sub);

-- Recuperação de senha por código de 6 dígitos enviado por e-mail. Só o hash do código fica no banco; vale por
-- 15 minutos, aceita poucas tentativas e é de uso único.
CREATE TABLE password_reset_codes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    code_hash   VARCHAR(64) NOT NULL,
    expires_at  TIMESTAMP   NOT NULL,
    attempts    INT         NOT NULL DEFAULT 0,
    used_at     TIMESTAMP,
    created_at  TIMESTAMP   NOT NULL
);
CREATE INDEX idx_password_reset_codes_user ON password_reset_codes (user_id);

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(120)  NOT NULL,
    email         VARCHAR(190)  NOT NULL,
    password_hash VARCHAR(100)  NOT NULL,
    created_at    TIMESTAMP     NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE accounts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT        NOT NULL REFERENCES users (id),
    name            VARCHAR(80)   NOT NULL,
    type            VARCHAR(20)   NOT NULL,
    initial_balance NUMERIC(14,2) NOT NULL DEFAULT 0,
    color           VARCHAR(9)    NOT NULL DEFAULT '#1B5E3F',
    archived        BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP     NOT NULL
);
CREATE INDEX ix_accounts_user ON accounts (user_id);

CREATE TABLE categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id),
    name       VARCHAR(60)  NOT NULL,
    type       VARCHAR(10)  NOT NULL,
    color      VARCHAR(9)   NOT NULL,
    icon       VARCHAR(40)  NOT NULL DEFAULT 'tag',
    archived   BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP    NOT NULL
);
CREATE INDEX ix_categories_user ON categories (user_id);

CREATE TABLE recurring_bills (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT        NOT NULL REFERENCES users (id),
    account_id   BIGINT        REFERENCES accounts (id),
    category_id  BIGINT        REFERENCES categories (id),
    description  VARCHAR(140)  NOT NULL,
    amount       NUMERIC(14,2) NOT NULL,
    type         VARCHAR(10)   NOT NULL,
    frequency    VARCHAR(10)   NOT NULL,
    start_date   DATE          NOT NULL,
    end_date     DATE,
    occurrences  INTEGER,
    notes        VARCHAR(500),
    active       BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP     NOT NULL
);
CREATE INDEX ix_recurring_user ON recurring_bills (user_id);

CREATE TABLE import_batches (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES users (id),
    account_id     BIGINT       NOT NULL REFERENCES accounts (id),
    source         VARCHAR(10)  NOT NULL,
    filename       VARCHAR(255),
    imported_count INTEGER      NOT NULL,
    created_at     TIMESTAMP    NOT NULL
);

CREATE TABLE transactions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT        NOT NULL REFERENCES users (id),
    account_id        BIGINT        NOT NULL REFERENCES accounts (id),
    category_id       BIGINT        REFERENCES categories (id),
    recurring_bill_id BIGINT        REFERENCES recurring_bills (id),
    import_batch_id   BIGINT        REFERENCES import_batches (id),
    description       VARCHAR(140)  NOT NULL,
    amount            NUMERIC(14,2) NOT NULL,
    type              VARCHAR(10)   NOT NULL,
    due_date          DATE          NOT NULL,
    paid              BOOLEAN       NOT NULL DEFAULT FALSE,
    notes             VARCHAR(500),
    external_id       VARCHAR(120),
    installment_number INTEGER,
    created_at        TIMESTAMP     NOT NULL,
    updated_at        TIMESTAMP     NOT NULL
);
CREATE INDEX ix_tx_user_date ON transactions (user_id, due_date);
CREATE INDEX ix_tx_account ON transactions (account_id);
CREATE INDEX ix_tx_category ON transactions (category_id);
CREATE UNIQUE INDEX uk_tx_recurring_date ON transactions (recurring_bill_id, due_date);
CREATE UNIQUE INDEX uk_tx_account_external ON transactions (account_id, external_id);

CREATE TABLE category_rules (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id),
    category_id BIGINT       NOT NULL REFERENCES categories (id),
    keyword     VARCHAR(120) NOT NULL,
    created_at  TIMESTAMP    NOT NULL,
    CONSTRAINT uk_rule_user_keyword UNIQUE (user_id, keyword)
);
